export function generateEstimateReport(result: {
  costEstimate: { materials: number; labor: number; equipment: number; overheads: number; contingency: number; total: number; currency: string; disclaimer: string };
  estimatedDuration: number;
  suggestedPhases: { name: string; duration: number; order: number; startMonth: number; endMonth: number }[];
  materialQuantities: Record<string, { quantity: number; unit: string; rate: number; cost: number }>;
  projectType?: string;
  location?: string;
  builtUpArea?: string;
}): string {
  const lines: string[] = [
    "=".repeat(50),
    "AAA PROMOTERZ & BUILDERS",
    "AI PROJECT ESTIMATE REPORT",
    "=".repeat(50),
    "",
    `Date: ${new Date().toLocaleDateString("en-IN")}`,
    `Project Type: ${result.projectType || "N/A"}`,
    `Location: ${result.location || "N/A"}`,
    `Built-up Area: ${result.builtUpArea || "N/A"} sq ft`,
    `Estimated Duration: ${result.estimatedDuration} months`,
    "",
    "-".repeat(50),
    "COST BREAKDOWN",
    "-".repeat(50),
    "",
    `Materials:       ₹${(result.costEstimate.materials / 100000).toFixed(2)}L`,
    `Labor:           ₹${(result.costEstimate.labor / 100000).toFixed(2)}L`,
    `Equipment:       ₹${(result.costEstimate.equipment / 100000).toFixed(2)}L`,
    `Overheads:       ₹${(result.costEstimate.overheads / 100000).toFixed(2)}L`,
    `Contingency:     ₹${(result.costEstimate.contingency / 100000).toFixed(2)}L`,
    "",
    `TOTAL ESTIMATED COST: ₹${(result.costEstimate.total / 100000).toFixed(1)}L`,
    "",
    `- ${result.costEstimate.disclaimer}`,
    "",
    "-".repeat(50),
    "SUGGESTED TIMELINE",
    "-".repeat(50),
    "",
  ];

  result.suggestedPhases.forEach((phase) => {
    lines.push(`Phase ${phase.order}: ${phase.name}`);
    lines.push(`  Duration: ${phase.duration} months (Month ${phase.startMonth + 1} - ${phase.endMonth})`);
    lines.push("");
  });

  lines.push("-".repeat(50));
  lines.push("MATERIAL QUANTITIES");
  lines.push("-".repeat(50));
  lines.push("");

  Object.entries(result.materialQuantities).forEach(([key, val]) => {
    lines.push(`  ${key}: ${val.quantity.toLocaleString()} ${val.unit} @ ₹${val.rate.toLocaleString()} = ₹${val.cost.toLocaleString()}`);
  });

  lines.push("");
  lines.push("=".repeat(50));
  lines.push("Generated by AAA Promoterz AI Estimator");
  lines.push("=".repeat(50));

  return lines.join("\n");
}

export function generateInvoiceReceipt(inv: {
  id: string;
  project: string;
  description: string;
  amount: number;
  status: string;
  issued: string;
  due: string;
  paid: string;
  method: string;
}): string {
  return [
    "=".repeat(50),
    "AAA PROMOTERZ & BUILDERS",
    "INVOICE / RECEIPT",
    "=".repeat(50),
    "",
    `Invoice No:    ${inv.id}`,
    `Project:       ${inv.project}`,
    `Description:   ${inv.description}`,
    `Amount:        $${(inv.amount / 1000).toFixed(0)}K ($${inv.amount.toLocaleString()})`,
    `Status:        ${inv.status.toUpperCase()}`,
    `Issued Date:   ${inv.issued}`,
    `Due Date:      ${inv.due}`,
    inv.paid ? `Paid Date:     ${inv.paid}` : "",
    inv.method ? `Payment Method: ${inv.method}` : "",
    "",
    "=".repeat(50),
    `Generated on ${new Date().toLocaleDateString("en-IN")}`,
    "=".repeat(50),
  ].filter(Boolean).join("\n");
}

